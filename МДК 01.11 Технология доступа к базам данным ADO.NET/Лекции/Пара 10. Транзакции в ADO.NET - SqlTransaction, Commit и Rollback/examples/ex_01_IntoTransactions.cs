// Транзакции

/*
    Транзакция - операция, позволяющая выполнить перечень sql-запросов.

    Принципы ACID:
    1. Atomicity(Атомарность) - все операции выполняются вместе или откатываются
    2. Consistency (согласованность) - после завершения сохраняются ограничения базы данных
    3. Isolation (изоляция) - параллельные транзакции не должны некорректно мешать друг другу
    4. Durability (долговечность) - после успешного подтверждения изменения сохраняются
*/