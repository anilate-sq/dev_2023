/*
    Пример строки подключения: Server=localhost;Database=coffee_shop;Trusted_Connection=True;TrustServerCertificate=True;

    Состав строки подключения:
    Server=Название сервера
    Database=Название базы данных
    Trusted_Connection=True - проверка подлинности Windows(используется только для MS SQL Server)
    Username / User ID= Имя пользователя
    Password=Пароль
    Encrypt=Кодировка - Шифрованное соединение(Опционально)
    TrustServerCertificate=True - Сертификат подлинности(используется только для MS SQL Server)
*/