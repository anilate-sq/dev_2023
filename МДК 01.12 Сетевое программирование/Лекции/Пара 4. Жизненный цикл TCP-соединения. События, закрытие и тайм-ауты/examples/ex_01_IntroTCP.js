// Жизненный цикл передачи TCP

/*
    Основные события:
    - connect - подключение
    - data - данные, получаемые из потока
    - end - когда удаленная сторона завершает отправку
    - close - закрытие сокета
    - error - ошибка при работе с сокетом
    - timeout - ограничение по времени на получение ответа

 */